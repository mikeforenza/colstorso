"""Measure WCAG 2.x contrast for ColsTorso semantic token pairs (light + dark).
Usage: python contrast.py  -> writes ../contrast-report.md and prints failures."""
import re, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
css = open(os.path.join(HERE, "..", "tokens.css")).read()
css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
def block(sel):
    m = re.search(re.escape(sel) + r"\s*\{(.*?)\n\}", css, re.S); return m.group(1)
def parse(b): return dict(re.findall(r"(--ct-[\w-]+)\s*:\s*([^;]+);", b))
light = parse(block(":root")); dark = {**light, **parse(block('[data-theme="dark"]'))}
def resolve(t, n, depth=0):
    v = t[n].strip()
    m = re.fullmatch(r"var\((--ct-[\w-]+)\)", v)
    return resolve(t, m.group(1), depth + 1) if m else v
def rgb(h):
    h = h.lstrip("#"); return [int(h[i:i+2], 16) / 255 for i in (0, 2, 4)]
def lum(h):
    c = [x / 12.92 if x <= 0.03928 else ((x + 0.055) / 1.055) ** 2.4 for x in rgb(h)]
    return 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2]
def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True); return (la + 0.05) / (lb + 0.05)
T = 4.5; U = 3.0  # text / non-text UI
P = []
for s in ["canvas", "raised", "sunken"]:
    for t in ["primary", "secondary", "muted"]:
        P.append((f"text-{t}", f"surface-{s}", T))
P += [("text-on-brand", "brand-primary", T), ("text-link", "surface-raised", T), ("text-brand", "surface-brand-subtle", T),
      ("text-primary", "surface-selected", T), ("text-on-accent", "brand-accent", T), ("text-inverse", "surface-inverse", T),
      ("border-strong", "surface-raised", U), ("border-focus", "surface-raised", U), ("focus-ring-color", "surface-canvas", U),
      ("brand-primary", "surface-raised", U)]
for s in ["success", "warning", "danger", "info"]:
    P += [(f"status-{s}-fg", f"status-{s}-bg", T), (f"status-{s}-fg", "surface-raised", T),
          (f"text-inverse", f"status-{s}-solid", T), (f"status-{s}-border", "surface-raised", U)]
for p in ["must", "should", "could"]:
    P += [(f"priority-{p}-fg", f"priority-{p}-bg", T), (f"priority-{p}-border", "surface-raised", U)]
for i in ["positive", "negative", "neutral"]:
    P += [(f"impact-{i}-fg", f"impact-{i}-bg", T), (f"impact-{i}-fg", "surface-raised", T)]
P += [("impact-store-line", "surface-raised", U), ("impact-control-line", "surface-raised", U)]
for f in ["fresh", "aging", "stale"]: P.append((f"freshness-{f}-fg", "surface-raised", T))
P.append(("freshness-offline-fg", "freshness-offline-bg", T))
for i in range(1, 7): P.append((f"chart-{i}", "surface-raised", U))
def name(n): return n if n.startswith("--") else ("--ct-" + n if n.startswith("focus") else "--ct-color-" + n)
rows, fails = [], 0
for fg, bg, need in P:
    r = []
    for th in (light, dark):
        a, b = resolve(th, name(fg)), resolve(th, name(bg))
        x = ratio(a, b); r.append((a, b, x, x >= need))
    fails += sum(1 for q in r if not q[3])
    rows.append((fg, bg, need, r))
out = ["# ColsTorso — measured contrast (WCAG 2.2)", "",
       "Generated by `scripts/contrast.py` from `tokens.css`. Text pairs need ≥ 4.5:1 (SC 1.4.3); UI/graphics pairs need ≥ 3:1 (SC 1.4.11).", "",
       "| Foreground token | Background token | Need | Light | Dark |", "|---|---|---|---|---|"]
for fg, bg, need, r in rows:
    cell = lambda q: f"{q[2]:.2f}:1 {'✅' if q[3] else '❌'} <sub>{q[0]} on {q[1]}</sub>"
    out.append(f"| `{name(fg)}` | `{name(bg)}` | {need}:1 | {cell(r[0])} | {cell(r[1])} |")
out += ["", f"**Pairs checked:** {len(rows)} × 2 themes. **Failures:** {fails}."]
open(os.path.join(HERE, "..", "contrast-report.md"), "w").write("\n".join(out) + "\n")
for fg, bg, need, r in rows:
    for th, q in zip(("light", "dark"), r):
        if not q[3]: print("FAIL", th, fg, "on", bg, f"{q[2]:.2f}", q[0], q[1])
print("pairs", len(rows), "fails", fails)
