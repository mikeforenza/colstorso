"""Generate TOKENS.md (the stable token API table) from tokens.css."""
import re, os
HERE = os.path.dirname(os.path.abspath(__file__)); D = os.path.join(HERE, "..")
raw = open(f"{D}/tokens.css").read()
def block(sel):
    return re.search(re.escape(sel) + r"\s*\{(.*?)\n\}", raw, re.S).group(1)
root, dark = block(":root"), block('[data-theme="dark"]')
dk = dict(re.findall(r"(--ct-[\w-]+)\s*:\s*([^;]+);", re.sub(r"/\*.*?\*/", "", dark, flags=re.S)))
sections, cur = [], None
for line in root.splitlines():
    m = re.match(r"\s*/\* -+ (\d+)\. (.*?) -+", line) or re.match(r"\s*/\* -+ (\d+)\. (.*?)(?:\(|$)", line)
    if m: cur = [m.group(2).strip(" -*/"), []]; sections.append(cur); continue
    t = re.match(r"\s*(--ct-[\w-]+)\s*:\s*([^;]+);\s*(?:/\*(.*?)\*/)?", line)
    if t and cur: cur[1].append((t.group(1), t.group(2).strip(), (t.group(3) or "").strip()))
out = ["# ColsTorso tokens — stable API (v1.0.0)", "",
 "Source of truth: `tokens.css`. Prefix: **`--ct-`**. Generated by `scripts/tokens_md.py`; regenerate after any change.", "",
 "## Rules for the build", "",
 "1. **These names are a public API.** Never rename or delete a token. To change a value, edit it in `tokens.css`. To replace a token, add the new one and mark the old one *deprecated* here for at least one release.",
 "2. Components use **semantic** tokens (`surface`, `text`, `border`, `brand`, `status`, `priority`, `impact`, `freshness`, `chart`). Primitives (`--ct-color-cobalt-600` and similar) exist only to build semantic tokens. Don't use them in components.",
 "3. Dark theme: set `data-theme=\"dark\"` on `<html>`. Only semantic tokens change, so a component that uses semantic tokens gets dark mode for free. Respect `prefers-color-scheme` on first load and store the user's choice.",
 "4. Fonts: `tokens.css` declares `@font-face` for Manrope and Inter from `./fonts/`. If the build serves CSS from another path, copy `fonts/` next to it or adjust the two `src:` URLs. Those are the only paths in the file.",
 "5. Breakpoints can't be used inside `@media` as `var()`. Use the literal values (480 / 768 / 1024 / 1280 / 1440px, mobile-first `min-width`).",
 "6. Composite type tokens are `font` shorthands: `font: var(--ct-type-h2);`.", "",
 "## Top-level groups", "",
 "| Group | Pattern | Purpose |", "|---|---|---|",
 "| Color primitives | `--ct-color-{cobalt,marigold,slate,green,amber,red,sky,flame}-{shade}` | Raw palette, don't use in components |",
 "| Surface | `--ct-color-surface-*` | Page, card, sunken, hover, selected, overlay, scrim, inverse, brand, nav |",
 "| Text | `--ct-color-text-*` | primary, secondary, muted, disabled, inverse, on-brand, on-accent, brand, link |",
 "| Border | `--ct-color-border-*` | subtle, default, strong (≥3:1), brand, focus |",
 "| Brand | `--ct-color-brand-*` | primary (+hover/active/subtle), accent (+subtle), ink |",
 "| Status | `--ct-color-status-{success,warning,danger,info}-{fg,bg,border,solid}` | Feedback and state |",
 "| Mission priority | `--ct-color-priority-{must,should,could}-{fg,bg,border}` | Matches `missions.priority` values in the build (Must / Should / Could) |",
 "| Impact | `--ct-color-impact-{positive,negative,neutral}-{fg,bg}`, `-store-line`, `-control-line`, `-band` | Results and charts |",
 "| Freshness | `--ct-color-freshness-{fresh,aging,stale}-fg`, `-offline-{bg,fg}` | Data age and offline banner |",
 "| Chart | `--ct-color-chart-1..6` | Categorical series, in order |",
 "| Typography | `--ct-font-family-*`, `--ct-font-size-*`, `--ct-font-weight-*`, `--ct-line-height-*`, `--ct-letter-spacing-*`, `--ct-type-*` | Type scale and composite styles |",
 "| Spacing | `--ct-space-*` | 4 px grid. The name is rem×100 (`-200` = 1rem = 16px) |",
 "| Radius | `--ct-radius-*` | none, sm, md, lg, xl, 2xl, pill, circle |",
 "| Shadow | `--ct-shadow-*` | none, sm, md, lg, overlay, nav |",
 "| Focus | `--ct-focus-ring*` | Focus ring width, offset, color and composite box-shadow |",
 "| Size | `--ct-size-*` | Touch targets, icons, nav sizes, content widths |",
 "| Motion | `--ct-motion-duration-*`, `--ct-motion-easing-*` | Reduced-motion sets durations to 0 |",
 "| Z-index | `--ct-z-*` | base, raised, sticky, nav, dropdown, overlay, modal, toast, tooltip |",
 "| Breakpoint | `--ct-breakpoint-*` | sm 480, md 768, lg 1024, xl 1280, 2xl 1440 (for JS and docs) |",
 "| Opacity | `--ct-opacity-*` | disabled, skeleton |", ""]
n = 0
for title, toks in sections:
    if not toks: continue
    out += [f"## {title}", "", "| Token | Light / default | Dark | Note |", "|---|---|---|---|"]
    for name, val, note in toks:
        n += 1
        d = dk.get(name, "same").strip()
        out.append(f"| `{name}` | `{val}` | `{d}` | {note} |")
    out.append("")
out.insert(3, f"**{n} tokens.** Contrast for every semantic text and UI pair is measured in [`contrast-report.md`](contrast-report.md).\n")
out += ["## Changelog", "", "- **1.0.0** (2026-10-11): first release."]
open(f"{D}/TOKENS.md", "w").write("\n".join(out) + "\n")
print("tokens", n)
